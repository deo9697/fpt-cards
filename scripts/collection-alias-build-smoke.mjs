import assert from 'node:assert/strict';
import { buildCollectionAliases } from './collection-alias-build-core.mjs';
import { enrichCollectionAliases, collectionAliasGaps, matchesCollectionQuery } from '../js/collection-search.js';
const en=new Map([['2511','Same'],['10000','English'],['20000','New']]);
const it=new Map([['2511','Same'],['10000','Italiano']]);
const reviewed=[{game:'yugioh',catalogCardId:'20000',expectedEnglishName:'New',aliases:['Nuova'],source:'review',reviewedAt:'2026-09-14'}];
const built=buildCollectionAliases(en,it,reviewed,{'10000':['English','Vecchio nome']});
assert.deepEqual(built.aliases['2511'],['Same']);
assert.deepEqual(built.aliases['10000'],['English','Italiano','Vecchio nome']);
assert.deepEqual(built.aliases['20000'],['New','Nuova']);
assert.equal(built.report.missingItalian.length,0);
assert.equal(built.report.retainedAliases.length,1);
assert.throws(()=>buildCollectionAliases(en,it,[{...reviewed[0],expectedEnglishName:'Wrong'}]));
assert.throws(()=>buildCollectionAliases(en,it,reviewed,{'99999':['Removed']}));
assert.equal(buildCollectionAliases(en,it,[]).report.missingItalian[0].catalogCardId,'20000');
const mine=[{id:'mine',game:'yugioh',catalogCardId:'999999999',cardName:'English name'}, {id:'op',game:'onepiece',catalogCardId:'999999999',cardName:'Different game'}, {id:'legacy',game:'yugioh',cardName:'Unknown'}];
const team=[{id:'team',game:'yugioh',catalogCardId:'999999999',cardName:'Nome italiano'}, {id:'other',game:'yugioh',catalogCardId:'888888888',cardName:'Altra carta'}];
const before=JSON.stringify({mine,team});
const enriched=enrichCollectionAliases({mine,team});
assert(matchesCollectionQuery(enriched.mine[0],'nome italiano'));
assert(!matchesCollectionQuery(enriched.mine[1],'nome italiano'));
assert(!matchesCollectionQuery(enriched.mine[2],'nome italiano'));
assert.equal(JSON.stringify({mine,team}),before,'Enrichment must not mutate source rows');
assert.deepEqual(enrichCollectionAliases(enriched),enriched,'Repeated sync must not duplicate aliases');
const gaps=collectionAliasGaps([...enriched.mine,...enriched.team]);
assert.equal(gaps[0].catalogCardId,'999999999');
assert.equal(gaps[0].printings,2);
assert(gaps[0].knownNames.includes('Nome italiano'));
console.log('PASS dictionary validation, retained/manual aliases, coverage, exact-ID/game enrichment, legacy, idempotence, priority report');
