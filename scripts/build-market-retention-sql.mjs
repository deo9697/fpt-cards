write('scripts/market-snapshot-retention-dry-run.sql',`-- GENERATED by scripts/build-market-retention-sql.mjs. No live execution.
-- Standalone, SELECT-only classification; requires full row visibility (no RLS filtering).
begin transaction isolation level repeatable read read only;
set local statement_timeout='60s';

select conrelid::regclass as referencing_table,conname,pg_get_constraintdef(oid) as definition
from pg_constraint where contype='f' and confrelid='public.market_price_snapshots'::regclass;

select p.oid::regprocedure as reader_or_writer from pg_proc p join pg_namespace n on n.oid=p.pronamespace
where n.nspname='public' and p.prokind='f'
  and p.prosrc ~ 'market_(price_snapshots|active_price_snapshots|derived_price_snapshots|latest_prices)';

with recursive dependencies(oid) as (
  select 'public.market_price_snapshots'::regclass::oid
  union
  select r.ev_class from dependencies x
    join pg_depend d on d.refobjid=x.oid and d.refclassid='pg_class'::regclass
    join pg_rewrite r on d.classid='pg_rewrite'::regclass and r.oid=d.objid
) select oid::regclass as dependent_relation from dependencies;

with policy as materialized (
${policy}
), totals as (select sum(estimated_row_bytes) as total_bytes from policy)
select bucket,provider,price_type,grouping(bucket,provider,price_type) as grouping_mask,
  count(*) as rows,sum(estimated_row_bytes) as estimated_logical_bytes,
  round(sum(estimated_row_bytes)::numeric/nullif((select total_bytes from totals),0)
    * pg_total_relation_size('public.market_price_snapshots')) as allocated_relation_bytes_estimate,
  min(captured_at) as min_captured_at,max(captured_at) as max_captured_at,
  count(*) filter(where fk_referenced) as fk_referenced_rows,
  max(unknown_fk_blockers) as unknown_fk_blockers
from policy group by grouping sets ((bucket),(bucket,provider),(bucket,provider,price_type),())
order by grouping_mask desc,bucket,provider,price_type;
rollback;
`);
write('supabase/manual/market-snapshot-retention-design.sql',`-- GENERATED by scripts/build-market-retention-sql.mjs. PREPARED, NOT APPLIED.
-- Creates private maintenance functions; does NOT execute cleanup or schedule it.
-- Never expose fpt_retention in PostgREST's exposed schemas.
begin;
create schema if not exists fpt_retention;
revoke all on schema fpt_retention from public,anon,authenticated;
grant usage on schema fpt_retention to service_role;

create or replace function fpt_retention.classify_market_snapshots()
returns table(id uuid,provider text,price_type text,captured_at timestamptz,
  estimated_row_bytes bigint,bucket text,reason text,fk_referenced boolean,unknown_fk_blockers bigint)
language sql stable security invoker set search_path=pg_catalog as $policy$
${policy}
$policy$;
revoke all on function fpt_retention.classify_market_snapshots() from public,anon,authenticated;
grant execute on function fpt_retention.classify_market_snapshots() to service_role;

create or replace function fpt_retention.cleanup_market_snapshots(
  dry_run boolean default true,max_rows integer default 100)
returns table(snapshot_id uuid,action text)
language plpgsql security invoker set search_path=pg_catalog as $cleanup$
begin
  if not (current_user in ('postgres','service_role') or exists (
    select 1 from pg_catalog.pg_roles where rolname=current_user and rolsuper
  )) then raise exception 'Maintenance requires service_role or database admin (postgres/superuser)'; end if;
  if dry_run is null or max_rows is null or max_rows<1 or max_rows>1000 then
    raise exception 'dry_run must be boolean; max_rows must be between 1 and 1000';
  end if;
  if dry_run then
    return query select p.id,'would_delete'::text from fpt_retention.classify_market_snapshots() p
      where p.bucket='cleanup_candidate' order by p.captured_at,p.id limit max_rows;
    return;
  end if;

  -- A stale repeatable-read snapshot could miss a concurrently committed reference.
  -- Require READ COMMITTED, then lock before evaluating the fresh classifier snapshot.
  if current_setting('transaction_isolation')<>'read committed' then
    raise exception 'Cleanup requires READ COMMITTED isolation';
  end if;
  -- NOWAIT fails instead of interfering with an active price sync / reference writer.
  -- Locks also prevent new references or FK DDL during this bounded transaction.
  lock table public.market_price_snapshots,public.market_current_price_snapshots,
    public.market_price_events in share row exclusive mode nowait;
  if exists(select 1 from fpt_retention.classify_market_snapshots() where unknown_fk_blockers>0) then
    raise exception 'Unknown snapshot FK: audit required';
  end if;
  if exists(select 1 from pg_catalog.pg_trigger where tgrelid='public.market_price_snapshots'::regclass
    and not tgisinternal and (tgtype::int & 8)<>0) then
    raise exception 'Unreviewed DELETE trigger: audit required';
  end if;
  if exists(select 1 from pg_catalog.pg_rewrite where ev_class='public.market_price_snapshots'::regclass
    and rulename<>'_RETURN') then raise exception 'Unreviewed snapshot rule: audit required'; end if;

  return query
    with candidates as materialized (
      select p.id from fpt_retention.classify_market_snapshots() p
      where p.bucket='cleanup_candidate' order by p.captured_at,p.id limit max_rows
    ), removed as (
      delete from public.market_price_snapshots s using candidates c
      where s.id=c.id
        -- Defense in depth: no caller-provided IDs and fresh FK guards under locks.
        and not exists(select 1 from public.market_current_price_snapshots cp where cp.snapshot_id=s.id)
        and not exists(select 1 from public.market_price_events e
          where e.previous_snapshot_id=s.id or e.current_snapshot_id=s.id)
      returning s.id
    ) select r.id,'deleted'::text from removed r;
end;
$cleanup$;
revoke all on function fpt_retention.cleanup_market_snapshots(boolean,integer) from public,anon,authenticated;
grant execute on function fpt_retention.cleanup_market_snapshots(boolean,integer) to service_role;
commit;
-- No invocation is included. One batch per short transaction, never a large loop.
-- Caller must set statement_timeout (e.g. 30s) BEFORE each independently authorized call.
`);
