// Build-time enrichment only. Never run by the live collection filter.
import { readFile, writeFile } from 'node:fs/promises';
import { buildCollectionAliases } from './collection-alias-build-core.mjs';
import { collectionNameAliases as previous } from '../js/collection-name-aliases.js';

const endpoint = 'https://db.ygoprodeck.com/api/v7/cardinfo.php';
const catalogs = await Promise.all(['en', 'it'].map(async language => {
  const response = await fetch(`${endpoint}${language === 'it' ? '?language=it' : ''}`, { signal: AbortSignal.timeout(120000) });
  if (!response.ok) throw new Error(`Catalog ${language}: HTTP ${response.status}`);
  const { data } = await response.json();
  if (!Array.isArray(data) || data.length < 1000) throw new Error(`Incomplete ${language} catalog`);
  return new Map(data.map(card => [String(card.id), card.name]));
}));
const [english, italian] = catalogs;
if (english.size < Object.keys(previous).length || italian.size < Object.keys(previous).length * 0.9) throw Error('Catalog coverage dropped unexpectedly');
const reviewed = JSON.parse(await readFile(new URL('./data/collection-search-reviewed-aliases.json', import.meta.url), 'utf8'));
const { aliases, report } = buildCollectionAliases(english, italian, reviewed, previous);
if (Object.keys(aliases).length < 1000) throw new Error('Refusing to replace dictionary with incomplete aliases');
const output = `// Generated by scripts/build-collection-search-aliases.mjs; source: YGOPRODeck EN/IT, ${new Date().toISOString().slice(0,10)}.\n// Text aliases only, joined on the provider ID; never an identity or artwork registry.\nexport const collectionNameAliases = ${JSON.stringify(aliases)};\n`;
await writeFile(new URL('../js/collection-name-aliases.js', import.meta.url), output);
await writeFile(new URL('../docs/collection-alias-coverage.json', import.meta.url), JSON.stringify(report,null,2)+'\n');
console.log(`Generated ${Object.keys(aliases).length} bilingual aliases (${Buffer.byteLength(output)} bytes)`);
console.log(`Missing Italian: ${report.missingItalian.length}; retained old aliases: ${report.retainedAliases.length}; changed IDs: ${report.changedIds.length}`);
