create or replace function public.list_ygo_market_variant_set_templates(p_token text)
returns table(set_prefix text, variant_number integer, rarity_canonical text, verified boolean, notes text, candidate_count integer)
language plpgsql stable security definer set search_path = public, extensions as $$
declare
  me text := public.session_member(p_token);
  admin boolean;
begin
  if me is null then raise exception 'Sessione scaduta'; end if;
  select role = 'admin' into admin from public.team_members where slug = me;
  if not coalesce(admin, false) then raise exception 'Operazione riservata agli admin'; end if;

  return query
    select t.set_prefix, t.variant_number, t.rarity_canonical, t.verified, t.notes, t.candidate_count
    from public.ygo_market_variant_set_templates t
    order by t.set_prefix, t.candidate_count nulls first, t.variant_number;
end;
$$;
