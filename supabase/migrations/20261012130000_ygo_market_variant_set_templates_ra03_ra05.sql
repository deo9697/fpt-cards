-- candidati ordinati per idProduct come fa il resolver, poi rango di prezzo
-- (trend) per posizione. Il profilo è lo stesso di RA01/RA02 già verificati:
--   RA01 n=7  (77 carte): V.5 la più cara in 76/77, rango medio V.1..V.7
