--   RA03 n=7  (63 carte): V.5 la più cara in 63/63, 6.3 6.5 4.6 2.3 1.0 3.9 3.3
--   RA04 n=7  (68 carte): V.5 la più cara in 68/68, 6.5 6.3 4.7 2.4 1.0 3.8 3.2
--   RA05 n=7  (73 carte): V.5 la più cara in 72/73, 6.5 6.4 4.9 2.4 1.0 3.3 3.6
--   RA03 n=2 (197), RA04 n=2 (184), RA05 n=2 (63): V.2 la più cara sempre
--   RA04 n=1  (19 carte, solo Quarter Century Secret Rare)
-- In RA05 la Starlight prende la posizione 5 che in RA01-RA04 è della
-- Quarter Century (RA05 non ha QCSR). Le carte a 6 rarità (5 in RA03, 6 in
-- RA04, 2 in RA05) NON hanno template: Collector's e Ultimate hanno prezzi
-- troppo vicini per distinguerle, restano ambiguous.
--
-- Additiva sui dati: non tocca le righe RA01/RA02 né mapping già risolti o
-- verificati (resolveYgoMarketVariant preserva verified/resolved esistenti).
-- Applicare PRIMA del deploy di market-sync che legge candidate_count.

