-- RA04 e RA05, più le stampe RA05 mancanti nel catalogo.
--
-- Problema: per i set Rarity Collection il feed Cardmarket ha un prodotto per
-- rarità (V.1..V.7) ma nessuna rarità nel JSON, quindi il prezzo live è il
-- minimo tra le varianti. Una Starlight (es. Imsety RA05-IT027, PSY-Framegear
-- Delta RA05-IT007) finiva col prezzo della Super.
--
-- Perché RA05 era "instabile": dentro lo stesso set convivono carte con 7
-- rarità e carte con 2 (Ultra + Starlight). Con 2 candidati V.2 è la
-- Starlight, mentre il template a 7 la leggerebbe come Ultra. Lo stesso vale
-- per RA03/RA04 (carte a 2 rarità Platinum Secret + Quarter Century). Da qui
-- la nuova colonna candidate_count: una riga template vale solo per prodotti
-- con esattamente quel numero di candidati. NULL = qualunque numero, cioè il
-- comportamento di RA01/RA02, che resta invariato.
--
-- Evidenza (feed ufficiale Cardmarket products_singles_3 + price_guide_3 del
